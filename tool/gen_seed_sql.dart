// Prints supabase/seed.sql from the games bundled in the app.
//   dart run tool/gen_seed_sql.dart > supabase/seed.sql
// test/seed_sql_test.dart fails if the file is out of date.
import 'package:preplay/models/game_model.dart';

String q(String s) => "'${s.replaceAll("'", "''")}'";
String arr(List<String> xs) => xs.isEmpty ? "'{}'::text[]" : 'ARRAY[${xs.map(q).join(', ')}]::text[]';

String seedSql() {
  final b = StringBuffer()
    ..writeln('-- Official games shown in "みんなの遊び". Generated by tool/gen_seed_sql.dart; do not edit.')
    ..writeln('-- Safe to run more than once; official games are updated to match the app.')
    ..writeln('insert into public.games (id, title, rules, origin, tags, topics) values');
  final rows = GameModel.mvpGames.map((g) =>
      '  (${q(g.id)}, ${q(g.title)}, ${q(g.rules)}, ${q('Preplay Official')}, ${arr(g.tags)}, ${arr(g.topics)})');
  b
    ..writeln(rows.join(',\n'))
    ..writeln('on conflict (id) do update set title = excluded.title, rules = excluded.rules,')
    ..writeln('  tags = excluded.tags, topics = excluded.topics')
    ..writeln("  where games.origin = 'Preplay Official';");
  return b.toString();
}

void main() => print(seedSql().trimRight());
